#!/usr/bin/env python3
"""Generate the app's top-view coordinates from the shipping PCB.

Uses the same footprint/outline reader as the firmware LED-layout generator.
RE1's origin is pin A, so apply the case model's documented shaft offset.
Run with --check to detect stale UI geometry after hardware edits.
"""
import argparse
import math
from pathlib import Path
import re
import runpy

ROOT = Path(__file__).resolve().parents[2]
BOARD = ROOT / "release/hardware/pcb/v5_8.kicad_pcb"
TARGET = ROOT / "macos/Sources/AgentPadCore/PhysicalLayout.swift"


def generate():
    reader = runpy.run_path(str(ROOT / "firmware/gen_led_layout.py"))
    text = BOARD.read_text()
    refs = reader["footprint_positions"](text)
    x0, y0, x1, y1 = reader["outline_bbox"](text)
    # The renderer intentionally uses the unmirrored KiCad XY frame: x right,
    # y down, USB at top. Fail rather than silently accept a new origin.
    assert (x0, y0) == (0.0, 0.0)
    edges = []
    for block in text.split('\n\t(gr_line')[1:]:
        block = block.split('\n\t)', 1)[0]
        if '(layer "Edge.Cuts")' not in block:
            continue
        edge = re.search(r'\(start\s+([-\d.]+)\s+([-\d.]+)\)\s+\(end\s+([-\d.]+)\s+([-\d.]+)\)', block)
        assert edge
        edges.append(edge.groups())
    vertices = set()
    for edge in edges:
        vertices.update([(float(edge[0]), float(edge[1])), (float(edge[2]), float(edge[3]))])
    assert len(edges) == len(vertices) == 8, "Expected the current eight-edge board outline"
    vertices = sorted(vertices, key=lambda p: math.atan2(p[1] - y1 / 2, p[0] - x1 / 2))
    case = (ROOT / "release/hardware/case/v2/agentpad13_case_v2.py").read_text()
    offset = re.search(r'EC11_ANCHOR_TO_SHAFT = \(([\d.]+), ([\d.]+)\)', case)
    assert offset
    # All PCB RE1 footprints currently have zero rotation. Guard the offset's
    # coordinate-frame assumption, as the CAD source does.
    encoder_block = next(b for b in text.split('\n\t(footprint ')[1:] if '(property "Reference" "RE1"' in b)
    rotation = re.search(r'\(at\s+[-\d.]+\s+[-\d.]+(?:\s+([-\d.]+))?\)', encoder_block)
    assert float(rotation[1] or 0) == 0
    shaft = (refs['RE1'][0] + float(offset[1]), refs['RE1'][1] + float(offset[2]))
    point = lambda xy: f"Point(x: {xy[0]:g}, y: {xy[1]:g})"
    switches = ',\n        '.join(point(refs[f'SW{i}']) for i in range(1, 14))
    outline = ',\n        '.join(point(xy) for xy in vertices)
    return f'''// Generated by macos/scripts/generate-layout.py. Do not hand-edit.
// PCB: release/hardware/pcb/v5_8.kicad_pcb; units: mm.
// Top view: x right, y down. RE1 uses the shaft, not the footprint anchor.
public enum PhysicalLayout {{
    public struct Point: Equatable, Sendable {{
        public let x: Double
        public let y: Double
    }}
    public static let width = {x1:g}
    public static let height = {float(y1)!r}
    // Index 0...12 is SW1...SW13, matching CODEX's physical positions.
    public static let switches: [Point] = [
        {switches}
    ]
    public static let outline: [Point] = [
        {outline}
    ]
    public static let encoder = {point(shaft)}
    public static let joystick = {point(refs['JS1'])}
    public static let touch = {point(refs['TP5'])}
    public static let usb = {point(refs['J1'])}
    // Back-side service switches; shown only as dashed reference marks.
    public static let boot = {point(refs['SW14'])}
    public static let reset = {point(refs['SW15'])}
}}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != source:
            raise SystemExit('UI geometry is stale. Run macos/scripts/generate-layout.py')
        print('PCB/UI geometry matches: 13 switches, RE1 shaft, JS1, TP5, USB and outline.')
    else:
        TARGET.write_text(source)
        print(TARGET.relative_to(ROOT))
